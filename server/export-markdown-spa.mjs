async function newestSourceModificationTime(root) {
	let newest = 0;
	for (const entry of await readdir(root, { withFileTypes: true })) {
		if (entry.name === "dist") continue;
		const entryPath = path.join(root, entry.name);
		if (entry.isDirectory()) newest = Math.max(newest, await newestSourceModificationTime(entryPath));
		else if (entry.isFile()) newest = Math.max(newest, (await stat(entryPath)).mtimeMs);
	}
	return newest;
}

async function ensureFrontendBundle() {
	const entryPath = path.join(REPOSITORY_ROOT, "src/frontend/main/index.txt.ts");
	const sharedRoot = path.join(REPOSITORY_ROOT, "src/shared");
	const outputPath = path.join(REPOSITORY_ROOT, "src/frontend/dist/index.txt.js");
	try {
		await stat(entryPath);
		await stat(sharedRoot);
	} catch (error) {
		if (error?.code === "ENOENT") return false;
		throw error;
	}

	let outputModifiedTime = 0;
	try {
		outputModifiedTime = (await stat(outputPath)).mtimeMs;
	} catch (error) {
		if (error?.code !== "ENOENT") throw error;
	}
	const sourceModifiedTime = Math.max(
		await newestSourceModificationTime(path.join(REPOSITORY_ROOT, "src/frontend")),
		await newestSourceModificationTime(sharedRoot),
	);
	if (outputModifiedTime >= sourceModifiedTime) return true;

	let esbuild;
	try {
		esbuild = await import("esbuild");
	} catch {
		throw new Error("Frontend sources are newer than the generated bundle. Run npm install in the repository so the server can rebuild it.");
	}
	const result = await esbuild.build({
		absWorkingDir: REPOSITORY_ROOT,
		entryPoints: [entryPath],
		external: ["moment", "src/plugin/*"],
		bundle: true,
		minify: false,
		treeShaking: true,
		platform: "browser",
		tsconfig: path.join(REPOSITORY_ROOT, "tsconfig.frontend.json"),
		write: false,
		outfile: outputPath,
	});
	let contents = result.outputFiles[0].text
		.replace(/this\.info_[^=]+=\s*(?:[^;{]|{(?:[^}]*{[^}]*})*[^}]*})*;/gm, "")
		.replace(/var .+?__require\(.+?\);/gm, "")
		.replace(/import_.+i18n.+;/gm, "'';");
	contents = `${FRONTEND_BANNER}\n\n${contents}`;
	await mkdir(path.dirname(outputPath), { recursive: true });
	await writeFile(outputPath, contents);
	console.log("[companion-app] rebuilt frontend bundle from current repository sources");
	return true;
}

export async function getMarkdownSpaApplicationVersion() {
	await ensureFrontendBundle();
	const hash = createHash("sha256");
	for (const relativePath of APPLICATION_SOURCE_PATHS) {
		try {
			hash.update(relativePath);
			hash.update(await readFile(path.join(REPOSITORY_ROOT, relativePath)));
		} catch (error) {
			if (error?.code === "ENOENT") return undefined;
			throw error;
		}
	}
	return hash.digest("hex");
}

function slugifyPath(value) {
	return value.replaceAll(" ", "-").replaceAll(/-{2,}/g, "-").toLowerCase();
}

function exportPath(sourcePath) {
	const output = slugifyPath(sourcePath.replaceAll("\\", "/"));
	return output.replace(/\.md$/i, ".html");
}

function slugifyHeading(value) {
	return String(value).normalize("NFKD")
		.replace(/[\u0300-\u036f]/g, "")
		.toLowerCase()
		.replace(/[^\p{L}\p{N}_ -]+/gu, "")
		.trim()
		.replace(/[\s_]+/g, "-") || "section";
}

function stringArray(value) {
	if (value == null) return [];
	if (Array.isArray(value)) return value.map(String).map((item) => item.trim()).filter(Boolean);
	const text = String(value).trim().replace(/^\[|\]$/g, "");
	return text ? text.split(",").map((item) => item.trim().replace(/^['"]|['"]$/g, "")).filter(Boolean) : [];
}

function parseFrontmatter(markdown) {
	const match = markdown.match(FRONTMATTER_PATTERN);
	if (!match) return { values: {}, text: "" };
	const values = {};
	const lines = match[1].split(/\r?\n/);
	for (let index = 0; index < lines.length; index++) {
		const property = lines[index].match(/^([\w-]+):\s*(.*)$/);
		if (!property) continue;
		const [, key, inline] = property;
		if (inline.trim()) {
			values[key] = inline.trim().replace(/^['"]|['"]$/g, "");
			continue;
		}
		const items = [];
		while (index + 1 < lines.length && /^\s*-\s+/.test(lines[index + 1])) {
			index++;
			items.push(lines[index].replace(/^\s*-\s+/, "").trim().replace(/^['"]|['"]$/g, ""));
		}
		values[key] = items;
	}
	return { values, text: match[1] };
}

function normalizeCallout(value) {
	return value.toLowerCase().replace(/[^a-z0-9]/g, "");
}

function withoutExcludedCallouts(markdown) {
	const lines = markdown.split(/\r?\n/);
	const kept = [];
	for (let index = 0; index < lines.length;) {
		const match = lines[index].match(/^>\s*\[!([^\]]+)\]\s*(.*)$/i);
		if (!match) {
			kept.push(lines[index++]);
			continue;
		}
		const excluded = normalizeCallout(match[1]) === "citingthisdocument" ||
			normalizeCallout(match[2]) === "citingthisdocument" ||
			normalizeCallout(match[2]) === "metadata";
		index++;
		while (index < lines.length && lines[index].startsWith(">")) {
			if (!excluded) kept.push(lines[index].replace(/^>\s?/, ""));
			index++;
		}
	}
	return kept.join("\n");
}

function getHeaders(markdown) {
	const used = new Map();
	const headers = [];
	for (const line of markdown.replace(FRONTMATTER_PATTERN, "").split(/\r?\n/)) {
		const match = line.match(/^(?:>\s*)*(#{1,6})\s+(.+?)\s*#*\s*$/);
		if (!match) continue;
		const heading = match[2].replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, (_value, target, label) => label || target).trim();
		const base = slugifyHeading(heading);
		const count = used.get(base) ?? 0;
		used.set(base, count + 1);
		headers.push({ heading, level: match[1].length, id: count ? `${base}-${count}` : base });
	}
	return headers;
}

function getSearchText(markdown, tags) {
	let text = withoutExcludedCallouts(markdown.replace(FRONTMATTER_PATTERN, ""));
	text = text.replace(/<style[\s\S]*?<\/style>|<script[\s\S]*?<\/script>/gi, " ");
	text = text.replace(/<[^>]+>/g, " ");
	for (const match of findObsidianTags(text).reverse()) text = `${text.slice(0, match.index)} ${text.slice(match.end)}`;
	text = text.replace(WIKILINK_PATTERN, (_match, _embed, target, label) => label?.trim() || target);
	text = text.replace(/!?(\[[^\]]*\])\([^)]*\)/g, "$1");
	text = text.replace(/[`*_~>#|]/g, " ");
	for (const tag of [...tags].sort((a, b) => b.length - a.length)) text = text.replaceAll(tag, " ");
	return text.replace(/\s+/g, " ").trim();
}

async function walkFiles(vaultRoot, relative = "") {
	const entries = await readdir(path.join(vaultRoot, relative), { withFileTypes: true });
	const files = [];
	for (const entry of entries) {
		if (entry.name === ".obsidian" || entry.name === ".trash" || entry.name === SERVER_DIRECTORY_NAME) continue;
		const sourcePath = relative ? `${relative}/${entry.name}` : entry.name;
		if (entry.isDirectory()) files.push(...await walkFiles(vaultRoot, sourcePath));
		else if (entry.isFile()) files.push(sourcePath);
	}
	return files;
}

function joinSearchValues(values) {
	return Array.isArray(values) ? values.map(String).join(SEARCH_VALUE_SEPARATOR) : "";
}

function createDirectDatabase(databasePath) {
	const database = new DatabaseSync(databasePath);
	database.exec(`
		PRAGMA journal_mode = WAL;
		PRAGMA synchronous = NORMAL;
		CREATE TABLE IF NOT EXISTS export_state (key TEXT PRIMARY KEY, value TEXT NOT NULL);
	`);
	const mode = database.prepare("SELECT value FROM export_state WHERE key = 'mode'").get()?.value;
	const recordFormat = database.prepare("SELECT value FROM export_state WHERE key = 'record_format'").get()?.value;
	if (mode !== "direct-markdown-spa" || recordFormat !== RECORD_FORMAT_VERSION) {
		database.exec(`
			DROP TABLE IF EXISTS search_documents;
			DROP TABLE IF EXISTS document_tags;
			DROP TABLE IF EXISTS navigation_entries;
			DROP TABLE IF EXISTS metadata_redirects;
			DROP TABLE IF EXISTS source_records;
			DROP TABLE IF EXISTS metadata_documents;
			DELETE FROM export_state;
		`);
	}
	database.exec(`
		CREATE VIRTUAL TABLE IF NOT EXISTS search_documents USING fts5(
			path, title, metadata, aliases, headers, tags, content,
			content = '', contentless_delete = 1, detail = column,
			tokenize = 'unicode61 remove_diacritics 2'
		);
		CREATE TABLE IF NOT EXISTS metadata_documents (
			document_id INTEGER PRIMARY KEY, export_path TEXT NOT NULL UNIQUE,
			source_path TEXT NOT NULL UNIQUE, source_basename TEXT NOT NULL, kind TEXT NOT NULL,
			title TEXT, inline_tags TEXT, frontmatter_tags TEXT, show_in_tree INTEGER NOT NULL,
			tree_order INTEGER NOT NULL, type TEXT, data TEXT NOT NULL
		);
		CREATE TABLE IF NOT EXISTS metadata_redirects (
			value TEXT PRIMARY KEY, export_path TEXT NOT NULL
		);
		CREATE TABLE IF NOT EXISTS source_records (
			filename TEXT PRIMARY KEY, export_path TEXT NOT NULL, source_modified_time REAL NOT NULL,
			source_size INTEGER NOT NULL, payload TEXT NOT NULL
		);
		CREATE TABLE IF NOT EXISTS document_tags (
			document_id INTEGER NOT NULL, source_path TEXT NOT NULL,
			tag_key TEXT NOT NULL, tag_path TEXT NOT NULL,
			parent_key TEXT NOT NULL, tag_name TEXT NOT NULL,
			inline_tag INTEGER NOT NULL, frontmatter_tag INTEGER NOT NULL,
			PRIMARY KEY(document_id, tag_key)
		) WITHOUT ROWID;
		CREATE TABLE IF NOT EXISTS navigation_entries (
			parent_path TEXT NOT NULL, entry_path TEXT NOT NULL, kind TEXT NOT NULL,
			name TEXT NOT NULL, source_path TEXT, export_path TEXT, type TEXT,
			PRIMARY KEY(parent_path, entry_path)
		) WITHOUT ROWID;
		CREATE INDEX IF NOT EXISTS metadata_redirects_export_path ON metadata_redirects(export_path);
		CREATE INDEX IF NOT EXISTS metadata_documents_basename ON metadata_documents(source_basename COLLATE NOCASE, tree_order, source_path);
		CREATE INDEX IF NOT EXISTS metadata_documents_tree ON metadata_documents(show_in_tree, tree_order, export_path);
		CREATE INDEX IF NOT EXISTS metadata_documents_kind_type ON metadata_documents(kind, type, tree_order, export_path);
		CREATE INDEX IF NOT EXISTS document_tags_key ON document_tags(tag_key, source_path COLLATE NOCASE, source_path, document_id);
		CREATE INDEX IF NOT EXISTS document_tags_parent ON document_tags(parent_key, tag_key, document_id);
	`);
	return database;
}

function createRecordStore(database) {
	const knownRecords = new Map(database.prepare(
		"SELECT filename, export_path FROM source_records"
	).all().map((row) => [row.filename, row.export_path]));
	const readRecord = database.prepare("SELECT payload FROM source_records WHERE filename = ?");
	return {
		knownRecords,
		get(filename) {
			const row = readRecord.get(filename);
			if (!row) return undefined;
			try {
				return { serialized: row.payload, record: JSON.parse(row.payload) };
			} catch {
				return undefined;
			}
		},
	};
}

function createDirectIndexWriter(database, recordStore) {
	const findDocument = database.prepare("SELECT document_id FROM metadata_documents WHERE export_path = ?");
	const deleteMetadata = database.prepare("DELETE FROM metadata_documents WHERE document_id = ?");
	const deleteRedirects = database.prepare("DELETE FROM metadata_redirects WHERE export_path = ?");
	const deleteSearch = database.prepare("DELETE FROM search_documents WHERE rowid = ?");
	const deleteTags = database.prepare("DELETE FROM document_tags WHERE document_id = ?");
	const deleteSourceRecord = database.prepare("DELETE FROM source_records WHERE filename = ?");
	const insertMetadata = database.prepare(`
		INSERT INTO metadata_documents(
			export_path, source_path, source_basename, kind, title, inline_tags, frontmatter_tags,
			show_in_tree, tree_order, type, data
		) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
		ON CONFLICT(export_path) DO UPDATE SET
			source_path=excluded.source_path, source_basename=excluded.source_basename,
			kind=excluded.kind, title=excluded.title, inline_tags=excluded.inline_tags,
			frontmatter_tags=excluded.frontmatter_tags, show_in_tree=excluded.show_in_tree,
			tree_order=excluded.tree_order, type=excluded.type, data=excluded.data
		RETURNING document_id
	`);
	const insertRedirect = database.prepare("INSERT OR IGNORE INTO metadata_redirects(value, export_path) VALUES (?, ?)");
	const insertSearch = database.prepare(`
		INSERT INTO search_documents(rowid, path, title, metadata, aliases, headers, tags, content)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?)
	`);
	const insertTag = database.prepare(`
		INSERT INTO document_tags(document_id, source_path, tag_key, tag_path, parent_key, tag_name, inline_tag, frontmatter_tag)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?)
	`);
	const insertSourceRecord = database.prepare(`
		INSERT OR REPLACE INTO source_records(filename, export_path, source_modified_time, source_size, payload)
		VALUES (?, ?, ?, ?, ?)
	`);
	const generated = new Set();
	let writtenRecords = 0;
	let reusedRecords = 0;
	let removedRecords = 0;

	function removeExportPath(exportedPath) {
		const documentId = findDocument.get(exportedPath)?.document_id;
		if (documentId === undefined) return;
		deleteRedirects.run(exportedPath);
		deleteSearch.run(documentId);
		deleteTags.run(documentId);
		deleteMetadata.run(documentId);
	}

	function collectTagPaths(data) {
		const paths = new Map();
		for (const [tags, source] of [[data.inlineTags ?? [], "inline"], [data.frontmatterTags ?? [], "frontmatter"]]) {
			for (const rawTag of tags) {
				const parts = String(rawTag).replace(/^#+/, "").split("/").map((part) => part.trim()).filter(Boolean);
				for (let index = 0; index < parts.length; index++) {
					const tagPath = parts.slice(0, index + 1).join("/");
					const tagKey = tagPath.toLowerCase();
					const entry = paths.get(tagKey) ?? {
						tagKey, tagPath, parentKey: parts.slice(0, index).join("/").toLowerCase(),
						tagName: parts[index], inline: 0, frontmatter: 0,
					};
					entry[source] = 1;
					paths.set(tagKey, entry);
				}
			}
		}
		return paths.values();
	}

	database.exec("BEGIN IMMEDIATE");
	function writeRecord(filename, record) {
		generated.add(filename);
		const serialized = JSON.stringify(record);
		const existing = recordStore.get(filename);
		if (existing?.serialized === serialized) {
			reusedRecords++;
			return;
		}
		const previous = existing?.record?.data;
		const data = record.data;
		if (previous?.exportPath) removeExportPath(previous.exportPath);
		removeExportPath(data.exportPath);
		const documentId = insertMetadata.get(
			data.exportPath, data.sourcePath, path.posix.basename(data.sourcePath),
			record.kind ?? "file", data.title ?? data.exportPath,
			joinSearchValues(data.inlineTags), joinSearchValues(data.frontmatterTags),
			data.showInTree ? 1 : 0, Number(data.treeOrder ?? 0), String(data.type ?? ""), JSON.stringify(data)
		).document_id;
		for (const value of record.redirectValues ?? []) {
			if (typeof value === "string" && value) insertRedirect.run(value, data.exportPath);
		}
		if (record.kind === "webpage" && record.search) {
			const tags = [...new Set([...(data.frontmatterTags ?? []), ...(data.inlineTags ?? [])])];
			insertSearch.run(
				documentId, data.exportPath, data.title ?? data.exportPath,
				record.search.metadata ?? "", joinSearchValues(data.aliases),
				joinSearchValues(record.search.headers), joinSearchValues(tags), record.search.content ?? ""
			);
			for (const tag of collectTagPaths(data)) {
				insertTag.run(documentId, data.sourcePath, tag.tagKey, tag.tagPath, tag.parentKey, tag.tagName, tag.inline, tag.frontmatter);
			}
		}
		insertSourceRecord.run(filename, data.exportPath, data.modifiedTime, data.sourceSize, serialized);
		writtenRecords++;
		if (writtenRecords % EXPORT_COMMIT_INTERVAL === 0) {
			database.exec("COMMIT");
			console.log(`[node-export] committed ${writtenRecords} changed records`);
			database.exec("BEGIN IMMEDIATE");
		}
	}

	function finish() {
		for (const [filename, exportPath] of recordStore.knownRecords) {
			if (generated.has(filename)) continue;
			removeExportPath(exportPath);
			deleteSourceRecord.run(filename);
			removedRecords++;
		}
		if (writtenRecords > 0 || removedRecords > 0) {
			database.exec("DELETE FROM navigation_entries");
			const insertNavigation = database.prepare(`
				INSERT OR IGNORE INTO navigation_entries(parent_path, entry_path, kind, name, source_path, export_path, type)
				VALUES (?, ?, ?, ?, ?, ?, ?)
			`);
			for (const row of database.prepare(`
				SELECT source_path, export_path, type FROM metadata_documents WHERE show_in_tree = 1
			`).iterate()) {
				const parts = String(row.source_path).replaceAll("\\", "/").split("/").filter(Boolean);
				let parent = "";
				for (const folderName of parts.slice(0, -1)) {
					const folderPath = parent ? `${parent}/${folderName}` : folderName;
					insertNavigation.run(parent, folderPath, "folder", folderName, null, null, null);
					parent = folderPath;
				}
				const filename = parts.at(-1) ?? row.source_path;
				insertNavigation.run(
					parent, row.source_path, "document",
					path.posix.basename(filename, path.posix.extname(filename)),
					row.source_path, row.export_path, row.type
				);
			}
		}
		database.prepare("INSERT OR IGNORE INTO export_state(key, value) VALUES ('mode', 'direct-markdown-spa')").run();
		database.prepare("INSERT OR IGNORE INTO export_state(key, value) VALUES ('record_format', ?)").run(RECORD_FORMAT_VERSION);
		database.exec("COMMIT");
		return { writtenRecords, reusedRecords, removedRecords };
	}

	return { writeRecord, finish };
}

function isCurrentSourceRecord(record, sourcePath, sourceStat) {
	const data = record?.data;
	return data?.sourcePath === sourcePath &&
		data.modifiedTime === sourceStat.mtimeMs &&
		data.sourceSize === sourceStat.size;
}

function resolveWikiTarget(rawTarget, sourcePath, documents, basenames) {
	const target = rawTarget.trim().replaceAll("\\", "/");
	if (!target) return undefined;
	const candidates = new Set([target]);
	if (!path.posix.extname(target)) candidates.add(`${target}.md`);
	const relative = path.posix.normalize(path.posix.join(path.posix.dirname(sourcePath), target));
	if (relative !== ".." && !relative.startsWith("../")) {
		candidates.add(relative);
		if (!path.posix.extname(relative)) candidates.add(`${relative}.md`);
	}
	for (const candidate of candidates) if (documents.has(candidate)) return documents.get(candidate);
	if (!target.includes("/")) return basenames.get(path.posix.basename(target).replace(/\.md$/i, ""));
	return undefined;
}

function collectDocumentLinks(markdown, document, documents, basenames) {
	const links = new Set();
	const attachments = new Set();
	function addTarget(rawTarget, embedded) {
		const target = resolveWikiTarget(rawTarget, document.sourcePath, documents, basenames);
		if (!target) return;
		links.add(target.exportPath);
		if (embedded || !target.sourcePath.toLowerCase().endsWith(".md")) attachments.add(target.exportPath);
	}
	for (const match of markdown.matchAll(WIKILINK_PATTERN)) {
		addTarget(match[2], Boolean(match[1]));
	}
	for (const match of markdown.matchAll(MARKDOWN_LINK_PATTERN)) {
		const rawTarget = match[2].split("#", 1)[0].trim();
		if (!rawTarget || /^(?:[a-z][a-z0-9+.-]*:|\/|#)/i.test(rawTarget)) continue;
		addTarget(rawTarget, Boolean(match[1]));
	}
	return { links, attachments };
}

